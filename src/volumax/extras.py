TEXT_PREVIEW_BYTES = 256 * 1024
IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".gif", ".bmp", ".webp", ".ico"}


# --------------------------------------------------------------------- script export

def _q_bat(s: str) -> str:
    return '"' + s.replace('"', '""').replace("%", "%%") + '"'


def _q_ps(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def export_create_script(
    engine_exe: str,
    archive: Path,
    sources: Sequence[Path],
    *,
    fmt: str = "7z",
    preset: str = "maximum",
    solid: bool = True,
    threads: int = 0,
    shell: str = "bat",        # bat | ps1 | sh
    encrypt: bool = False,
    encrypt_filenames: bool = False,
) -> str:
    """A ready-to-schedule script reproducing what the Create page would do.

    The password is NEVER written into the script: when ``encrypt`` is set the script asks
    for it at run time (7-Zip's bare ``-p`` prompt), so no secret ends up on disk.
    """
    prof = analyze_sources([Path(p) for p in sources])
    plan = plan_compression(fmt if fmt in ("7z", "zip") else "7z", preset=preset, profile=prof,
                            solid=solid, threads=threads)
    args = ["a", f"-t{fmt}", *plan.args, "-bsp1", "-snl"]
    if encrypt:
        args.append("-p")
        if fmt == "7z" and encrypt_filenames:
            args.append("-mhe=on")
        elif fmt == "zip":
            args.append("-mem=AES256")
    exe, out = str(engine_exe), str(archive)
    src = [str(s) for s in sources]
    note = f"Compression plan: {plan.description}"
    if shell == "sh":
        cmd = " ".join(shlex.quote(x) for x in [exe, *args, out, *src])
        return f"#!/bin/sh\n# Generated by VOLUMAX\n# {note}\nset -e\n{cmd}\n"
    if shell == "ps1":
        cmd = "& " + " ".join(_q_ps(x) for x in [exe, *args, out, *src])
        return (f"# Generated by VOLUMAX\n# {note}\n{cmd}\n"
                "if ($LASTEXITCODE -gt 1) { Write-Error \"7-Zip failed ($LASTEXITCODE)\"; exit $LASTEXITCODE }\n")
    cmd = " ".join(_q_bat(x) for x in [exe, *args, out, *src])
    return f"@echo off\r\nrem Generated by VOLUMAX\r\nrem {note}\r\n{cmd}\r\nexit /b %ERRORLEVEL%\r\n"


# ------------------------------------------------------------------------- compare

@dataclass
class CompareResult:
    ok: bool
    message: str = ""
    only_a: list[str] = field(default_factory=list)
    only_b: list[str] = field(default_factory=list)
    changed: list[str] = field(default_factory=list)
    same: int = 0

    @property
    def identical(self) -> bool:
        return self.ok and not (self.only_a or self.only_b or self.changed)


def compare_archives(manager, a: Path, b: Path, pw_a: str | None = None, pw_b: str | None = None) -> CompareResult:
    ra, ta = load_tree(manager, Path(a), pw_a)
    if ta is None:
        return CompareResult(False, f"Cannot read {Path(a).name}: {ra.message}")
    rb, tb = load_tree(manager, Path(b), pw_b)
    if tb is None:
        return CompareResult(False, f"Cannot read {Path(b).name}: {rb.message}")
    ma = {e.path: e for e in ta.entries if not e.is_dir}
    mb = {e.path: e for e in tb.entries if not e.is_dir}
    out = CompareResult(True)
    out.only_a = sorted(set(ma) - set(mb))
    out.only_b = sorted(set(mb) - set(ma))
    for name in sorted(set(ma) & set(mb)):
        ea, eb = ma[name], mb[name]
        if ea.size != eb.size or (ea.crc and eb.crc and ea.crc != eb.crc):
            out.changed.append(name)
        else:
            out.same += 1
    out.message = (f"{out.same} identical, {len(out.changed)} changed, "
                   f"{len(out.only_a)} only in A, {len(out.only_b)} only in B")
    return out


# --------------------------------------------------------------------------- find

@dataclass
class FindHit:
    archive: str
    member: str
    size: int


def find_in_archives(
    manager,
    folder: Path,
    pattern: str,
    *,
    recursive: bool = True,
    max_archives: int = 500,
    max_hits: int = 5000,
    cancel: Callable[[], bool] | None = None,
    progress: Callable[[int, str], None] | None = None,
) -> tuple[list[FindHit], list[str]]:
    """Search member names (wildcards, case-insensitive) inside every archive in ``folder``."""
    pat = pattern if any(c in pattern for c in "*?[") else f"*{pattern}*"
    pat = pat.lower()
    folder = Path(folder)
    files = folder.rglob("*") if recursive else folder.glob("*")
    archives: list[Path] = []
    try:
        for p in files:
            if p.is_file() and looks_like_archive(p):
                archives.append(p)
                if len(archives) >= max_archives:
                    break
    except OSError:
        pass
    hits: list[FindHit] = []
    unreadable: list[str] = []
    for i, arch in enumerate(archives):
        if cancel and cancel():
            break
        _, tree = load_tree(manager, arch)
        if tree is None:
            unreadable.append(arch.name)  # damaged or password-protected: reported, never fatal
        else:
            for e in tree.entries:
                if not e.is_dir and fnmatch.fnmatch(e.path.lower(), pat):
                    hits.append(FindHit(str(arch), e.path, e.size))
                    if len(hits) >= max_hits:
                        return hits, unreadable
        if progress:
            progress(int(100 * (i + 1) / len(archives)), arch.name)
    return hits, unreadable


# ------------------------------------------------------------------------ preview

@dataclass
class Preview:
    kind: str            # text | image | binary | error
    text: str = ""
    path: Path | None = None  # image file inside ``workdir``
    truncated: bool = False
    workdir: Path | None = None  # caller must call cleanup()

    def cleanup(self) -> None:
        if self.workdir:
            shutil.rmtree(self.workdir, ignore_errors=True)


def preview_member(manager, archive: Path, member: str, password: str | None = None,
                   max_bytes: int = 64 * 1024 * 1024) -> Preview:
    """Extract ONE member to a private temp dir and describe it (text/image/binary)."""
    work = Path(tempfile.mkdtemp(prefix="volumax_preview_"))
    try:
        _, tree = load_tree(manager, Path(archive), password)
        if tree is not None:
            ent = next((e for e in tree.entries if e.path == member), None)
            if ent is not None and ent.size > max_bytes:
                return Preview("error", f"Too large to preview ({ent.size // (1024 * 1024)} MB).", workdir=work)
        res = manager.extract(Path(archive), work, password=password, selected=[member], safe=True)
        if not res.success:
            return Preview("error", res.message or "Could not extract that file.", workdir=work)
        found = [p for p in work.rglob("*") if p.is_file() and not p.is_symlink()]
        if not found:
            return Preview("error", "Nothing was extracted (is it a folder?).", workdir=work)
        f = found[0]
        if f.suffix.lower() in IMAGE_EXTS:
            return Preview("image", path=f, workdir=work)
        raw = f.read_bytes()[: TEXT_PREVIEW_BYTES + 1]
        trunc = len(raw) > TEXT_PREVIEW_BYTES
        raw = raw[:TEXT_PREVIEW_BYTES]
        if b"\x00" in raw[:4096]:
            return Preview("binary", f"Binary file, {f.stat().st_size:,} bytes.", workdir=work)
        for enc in ("utf-8", "utf-16", "cp1252"):
            try:
                return Preview("text", raw.decode(enc), truncated=trunc, workdir=work)
            except UnicodeError:
                continue
        return Preview("binary", "Not displayable as text.", workdir=work)
    except Exception as exc:  # preview must never take the app down
        return Preview("error", f"Preview failed: {exc}", workdir=work)


# ------------------------------------------------------------------------ salvage

@dataclass
class SalvageResult:
    success: bool
    message: str
    folder: Path | None = None
    recovered: int = 0


def salvage(manager, archive: Path, dest_parent: Path, password: str | None = None,
            progress=None, cancel=None) -> SalvageResult:
    """Recover whatever is readable from a damaged archive into a fresh folder.

    7-Zip keeps extracting past bad entries; a non-zero exit with files on disk is a
    *partial success* here, not a failure.  Symlinks are removed afterwards.
    """
    archive = Path(archive)
    dest_parent = Path(dest_parent)
    base = dest_parent / f"{archive.stem}_salvaged"
    folder, n = base, 1
    while folder.exists():
        n += 1
        folder = dest_parent.joinpath(f"{base.name}_{n}")
    try:
        folder.mkdir(parents=True)
    except OSError as exc:
        return SalvageResult(False, f"Cannot create the output folder: {exc}")
    res = manager.engine.extract_archive(archive, folder, password=password, overwrite=True,
                                         progress=progress, cancel=cancel)
    for p in list(folder.rglob("*")):
        try:
            if p.is_symlink():
                p.unlink()
        except OSError:
            pass
    files = [p for p in folder.rglob("*") if p.is_file()]
    if res.success:
        return SalvageResult(True, f"Archive is intact: {len(files)} files extracted.", folder, len(files))
    if files:
        return SalvageResult(True, f"Recovered {len(files)} file(s); some data was damaged and could not be restored.",
                             folder, len(files))
    try:
        folder.rmdir()
    except OSError:
        pass
    return SalvageResult(False, res.message or "Nothing could be recovered.")


# ------------------------------------------------------- verify after create + hash

def sha256_file(path: Path) -> str:
    with open(path, "rb") as f:
        return file_digest(f, "sha256")


def write_sha256_sidecar(path: Path) -> Path:
    """``archive.7z.sha256`` in the standard ``<hash> *<name>`` format (works with sha256sum -c)."""
    path = Path(path)
    side = path.with_name(path.name + ".sha256")
    side.write_text(f"{sha256_file(path)} *{path.name}\n", encoding="utf-8")
    return side


def verify_sha256_sidecar(path: Path) -> tuple[bool, str]:
    path = Path(path)
    side = path.with_name(path.name + ".sha256")
    if not side.is_file():
        return False, "No .sha256 file next to the archive."
    try:
        expected = side.read_text(encoding="utf-8").split()[0].lower()
    except (OSError, IndexError):
        return False, "The .sha256 file is unreadable."
    actual = sha256_file(path)
    return (actual == expected, "Checksum matches." if actual == expected else "CHECKSUM MISMATCH — the file changed or is damaged.")


def verify_created(manager, archive: Path, password: str | None = None, sidecar: bool = False) -> tuple[bool, str]:
    """Re-test a freshly created archive (and optionally write its checksum file)."""
    res = manager.test_integrity(Path(archive), password=password)
    if not res.success:
        return False, f"Verification FAILED: {res.message}"
    note = "Verified OK"
    if sidecar:
        try:
            note += f"; checksum saved to {write_sha256_sidecar(archive).name}"
        except OSError as exc:
            note += f" (could not write checksum file: {exc})"
    return True, note
