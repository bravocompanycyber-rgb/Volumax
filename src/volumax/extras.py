"""Extra capabilities: script export, compare, find, preview, salvage, verify + checksum.

All functions are pure/synchronous and UI-free so they can run in worker threads and be
tested directly.  Nothing here scans drives on its own: every function only touches paths
the caller hands it.
"""

from __future__ import annotations

import fnmatch
import shlex
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Callable, Sequence

from .compat import file_digest, looks_like_archive
from .compression import analyze_sources, plan_compression
